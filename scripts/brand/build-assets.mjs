// Builds every Thrivie brand asset from the three approved master SVGs in
// public/brand/ (thrivie-mark.svg, thrivie-lockup.svg, thrivie-wordmark.svg).
//
// The masters are the single source of truth (mark: designer's vector file;
// wordmark: traced from the approved card, verified at 99.77% overlap; see
// design/brand/README.md). This script only changes colour and places the
// artwork on canvases. It never edits the shapes.
//
//   node scripts/brand/build-assets.mjs
//
// Needs Playwright's Chromium (preinstalled in CI images; `npx playwright install chromium` locally).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const BRAND = path.join(ROOT, "public/brand");
const ICONS = path.join(ROOT, "public/icons");
fs.mkdirSync(ICONS, { recursive: true });

const NAVY = "#1E3A64"; // brand navy (card centre)
const DEEP = "#0C1B30"; // card corners
const GLOW = "#355A8F"; // card highlight

// ---------------------------------------------------------------- masters --
const VARIANTS = ["mark", "lockup", "wordmark"];
const master = Object.fromEntries(
  VARIANTS.map((v) => {
    const svg = fs.readFileSync(path.join(BRAND, `thrivie-${v}.svg`), "utf8");
    const [, w, h] = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
    const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
    if (!paths.length) throw new Error(`no paths in ${v}`);
    return [v, { svg, w: Number(w), h: Number(h), paths }];
  }),
);

const recolor = (svg, fill) => svg.replace(/fill="#fff"/g, `fill="${fill}"`);
const inner = (v, fill = "#fff", opacity = 1) =>
  `<g fill="${fill}"${opacity < 1 ? ` fill-opacity="${opacity}"` : ""}>${master[v].paths.map((d) => `<path d="${d}"/>`).join("")}</g>`;
/** Place a variant at (x, y) scaled to `height` (aspect ratio preserved). */
const place = (v, x, y, height, fill, opacity) => {
  const s = height / master[v].h;
  return `<g transform="translate(${x} ${y}) scale(${s})">${inner(v, fill, opacity)}</g>`;
};

// Navy versions: colour change only.
for (const v of VARIANTS) fs.writeFileSync(path.join(BRAND, `thrivie-${v}-navy.svg`), recolor(master[v].svg, NAVY));

// Ghost mark for the brand background: same shapes, low opacity.
fs.writeFileSync(
  path.join(BRAND, "thrivie-mark-ghost.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${master.mark.w} ${master.mark.h}">${inner("mark", "#fff", 0.07)}</svg>`,
);

// Inline data for the <Logo> component (no network request, crisp at any size).
fs.writeFileSync(
  path.join(ROOT, "src/components/logoData.ts"),
  `// Generated by scripts/brand/build-assets.mjs from public/brand/*.svg. Do not edit by hand.\n` +
    `export const LOGO = ${JSON.stringify(Object.fromEntries(VARIANTS.map((v) => [v, { w: master[v].w, h: master[v].h, paths: master[v].paths }])))} as const;\n` +
    `export type LogoVariant = keyof typeof LOGO;\n`,
);

// ------------------------------------------------------------------- icons --
// White mark centred on solid brand navy. `fit` is the mark's share of the
// canvas: 0.64 keeps every tip inside iOS/Android rounded shapes; maskable icons
// use 0.54 so the whole mark sits inside Android's 80% safe circle.
function iconSvg(size, fit) {
  const h = size * fit;
  const w = (h * master.mark.w) / master.mark.h;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="${NAVY}"/>${place("mark", (size - w) / 2, (size - h) / 2, h, "#fff")}</svg>`;
}
fs.writeFileSync(path.join(ROOT, "public/icon.svg"), iconSvg(512, 0.74)); // favicon: same framing as the 16/32 px PNGs

function cardBackground(w, h) {
  return `<defs><radialGradient id="bg" cx="0.62" cy="0.3" r="0.95"><stop offset="0" stop-color="${GLOW}"/><stop offset="0.42" stop-color="${NAVY}"/><stop offset="1" stop-color="${DEEP}"/></radialGradient></defs><rect width="${w}" height="${h}" fill="url(#bg)"/>`;
}
// Open Graph card: lockup centred on the navy gradient, ghost mark on the left.
function ogSvg() {
  const W = 1200, H = 630, lh = 470, lw = (lh * master.lockup.w) / master.lockup.h;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">${cardBackground(W, H)}${place("mark", -260, -40, 760, "#fff", 0.07)}${place("lockup", (W - lw) / 2, (H - lh) / 2, lh, "#fff")}</svg>`;
}

const jobs = [
  // [file, svg, width, height, transparent]
  ...[16, 32].map((s) => [path.join(ICONS, `icon-${s}.png`), iconSvg(s, 0.74), s, s, false]),
  [path.join(ICONS, "apple-touch-icon.png"), iconSvg(180, 0.64), 180, 180, false],
  [path.join(ICONS, "icon-192.png"), iconSvg(192, 0.64), 192, 192, false],
  [path.join(ICONS, "icon-512.png"), iconSvg(512, 0.64), 512, 512, false],
  [path.join(ICONS, "icon-maskable-512.png"), iconSvg(512, 0.54), 512, 512, false],
  [path.join(BRAND, "og-image.png"), ogSvg(), 1200, 630, false],
];
// Transparent high-resolution PNG fallbacks of each master, white and navy.
for (const v of VARIANTS) {
  const W = v === "wordmark" ? 2400 : 2048, H = Math.round((W * master[v].h) / master[v].w);
  for (const [suffix, fill] of [["", "#fff"], ["-navy", NAVY]]) {
    jobs.push([path.join(BRAND, `thrivie-${v}${suffix}@${W}w.png`), `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${master[v].w} ${master[v].h}">${inner(v, fill)}</svg>`, W, H, true]);
  }
}

const browser = await chromium.launch();
const page = await browser.newPage();
for (const [file, svg, w, h, transparent] of jobs) {
  await page.setViewportSize({ width: w, height: h });
  const src = "data:image/svg+xml;base64," + Buffer.from(svg).toString("base64");
  await page.setContent(`<html><body style="margin:0;background:transparent"><img src="${src}" width="${w}" height="${h}" style="display:block"></body></html>`);
  await page.waitForFunction(() => document.images[0].complete);
  await page.screenshot({ path: file, clip: { x: 0, y: 0, width: w, height: h }, omitBackground: transparent });
}
await browser.close();

// favicon.ico with the 16 and 32 px PNGs embedded (supported by every browser).
const pngs = [16, 32].map((s) => [s, fs.readFileSync(path.join(ICONS, `icon-${s}.png`))]);
const header = Buffer.alloc(6 + 16 * pngs.length);
header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(pngs.length, 4);
let offset = header.length;
pngs.forEach(([s, buf], i) => {
  const o = 6 + 16 * i;
  header.writeUInt8(s, o); header.writeUInt8(s, o + 1); header.writeUInt16LE(1, o + 4); header.writeUInt16LE(32, o + 6);
  header.writeUInt32LE(buf.length, o + 8); header.writeUInt32LE(offset, o + 12); offset += buf.length;
});
fs.writeFileSync(path.join(ROOT, "public/favicon.ico"), Buffer.concat([header, ...pngs.map(([, b]) => b)]));

console.log(`Built ${jobs.length} images, favicon.ico, navy + ghost SVGs and src/components/logoData.ts`);
